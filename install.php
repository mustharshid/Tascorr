/**
 * install.php - Web-based interactive installation wizard for Tascorr.
 * Guided installation script for Plesk. Set up database, run schema, write .env,
 * create superadmin, and finalize installation.
 */

// If installer is called via AJAX
if (isset($_GET['action'])) {
    header('Content-Type: application/json');
    $action = $_GET['action'];

    try {
        switch ($action) {
            case 'test_db':
                $data = json_decode(file_get_contents('php://input'), true);
                $host = $data['host'] ?? 'localhost';
                $port = $data['port'] ?? '3306';
                $dbname = $data['dbname'] ?? '';
                $username = $data['username'] ?? '';
                $password = $data['password'] ?? '';

                if (empty($dbname) || empty($username)) {
                    throw new Exception('Database name and username are required.');
                }

                $dsn = "mysql:host=$host;port=$port;dbname=$dbname;charset=utf8mb4";
                $options = [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                    PDO::ATTR_TIMEOUT => 5
                ];
                $pdo = new PDO($dsn, $username, $password, $options);
                
                echo json_encode(['success' => true, 'message' => 'Database connection successful.']);
                exit;

            case 'install_schema':
                $data = json_decode(file_get_contents('php://input'), true);
                $host = $data['host'] ?? 'localhost';
                $port = $data['port'] ?? '3306';
                $dbname = $data['dbname'] ?? '';
                $username = $data['username'] ?? '';
                $password = $data['password'] ?? '';

                $dsn = "mysql:host=$host;port=$port;dbname=$dbname;charset=utf8mb4";
                $pdo = new PDO($dsn, $username, $password, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);

                if (!file_exists('install.sql')) {
                    throw new Exception('install.sql schema file not found in root.');
                }

                $sql = file_get_contents('install.sql');
                
                // Execute schema. We execute statement by statement or using PDO exec for multi-query
                // Note: PDO exec is capable of executing multiple queries separated by semicolons in pdo_mysql
                $pdo->exec($sql);

                // Fetch created tables to present checklist
                $stmt = $pdo->query("SHOW TABLES");
                $tables = $stmt->fetchAll(PDO::FETCH_COLUMN);

                echo json_encode(['success' => true, 'message' => 'Schema installed successfully.', 'tables' => $tables]);
                exit;

            case 'save_env':
                $data = json_decode(file_get_contents('php://input'), true);
                $host = $data['host'] ?? 'localhost';
                $port = $data['port'] ?? '3306';
                $dbname = $data['dbname'] ?? '';
                $username = $data['username'] ?? '';
                $password = $data['password'] ?? '';

                // Generate random JWT Secret (256-bit representation)
                $jwtSecret = base64_encode(random_bytes(32));

                $envContent = "# =======================================================\n";
                $envContent .= "# Auto-generated by Tascorr Web Installer Wizard\n";
                $envContent .= "# Generated: " . date('Y-m-d H:i:s') . "\n";
                $envContent .= "# =======================================================\n\n";
                $envContent .= "PORT=5005\n";
                $envContent .= "DATABASE_URL=\"mysql://$username:" . urlencode($password) . "@$host:$port/$dbname\"\n";
                $envContent .= "JWT_SECRET=\"$jwtSecret\"\n";
                $envContent .= "NODE_ENV=\"production\"\n";
                $envContent .= "ALLOWED_ORIGINS=\"https://tascorr.thinksafe.mv\"\n";

                if (file_put_contents('.env', $envContent) === false) {
                    throw new Exception('Failed to write .env file. Check directory permissions.');
                }

                // Apply .htaccess security rule blocking direct web access to .env
                $htaccessRule = "<Files .env>\nOrder allow,deny\nDeny from all\n</Files>\n";
                if (file_exists('.htaccess')) {
                    $existing = file_get_contents('.htaccess');
                    if (strpos($existing, '<Files .env>') === false) {
                        file_put_contents('.htaccess', $existing . "\n" . $htaccessRule);
                    }
                } else {
                    file_put_contents('.htaccess', $htaccessRule);
                }

                echo json_encode(['success' => true, 'message' => '.env file successfully generated and secured.']);
                exit;

            case 'create_superadmin':
                $data = json_decode(file_get_contents('php://input'), true);
                $host = $data['host'] ?? 'localhost';
                $port = $data['port'] ?? '3306';
                $dbname = $data['dbname'] ?? '';
                $username = $data['username'] ?? '';
                $password = $data['password'] ?? '';
                
                $saEmail = $data['sa_email'] ?? '';
                $saPassword = $data['sa_password'] ?? '';

                if (empty($saEmail) || empty($saPassword)) {
                    throw new Exception('Superadmin email and password are required.');
                }

                // Password complexity check: 12+ chars, mixed case, number, symbol
                if (strlen($saPassword) < 12) {
                    throw new Exception('Password must be at least 12 characters.');
                }
                if (!preg_match('/[A-Z]/', $saPassword) || !preg_match('/[a-z]/', $saPassword)) {
                    throw new Exception('Password must contain both uppercase and lowercase letters.');
                }
                if (!preg_match('/[0-9]/', $saPassword)) {
                    throw new Exception('Password must contain at least one number.');
                }
                if (!preg_match('/[^a-zA-Z0-9]/', $saPassword)) {
                    throw new Exception('Password must contain at least one symbol/special character.');
                }

                // Hash password using Bcrypt with cost factor 12
                $passwordHash = password_hash($saPassword, PASSWORD_BCRYPT, ['cost' => 12]);

                $dsn = "mysql:host=$host;port=$port;dbname=$dbname;charset=utf8mb4";
                $pdo = new PDO($dsn, $username, $password, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);

                // Insert Superadmin User referencing Rank ID 999 (created in install.sql)
                $stmt = $pdo->prepare("INSERT INTO `users` 
                    (`tenant_id`, `email`, `password_hash`, `first_name`, `last_name`, `rank_id`, `status`, `created_at`, `updated_at`) 
                    VALUES (0, ?, ?, 'Global', 'Superadmin', 999, 'active', NOW(), NOW())");
                $stmt->execute([$saEmail, $passwordHash]);

                echo json_encode(['success' => true, 'message' => 'Superadmin account created successfully.']);
                exit;

            case 'seed_data':
                $data = json_decode(file_get_contents('php://input'), true);
                $host = $data['host'] ?? 'localhost';
                $port = $data['port'] ?? '3306';
                $dbname = $data['dbname'] ?? '';
                $username = $data['username'] ?? '';
                $password = $data['password'] ?? '';

                $dsn = "mysql:host=$host;port=$port;dbname=$dbname;charset=utf8mb4";
                $pdo = new PDO($dsn, $username, $password, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);

                // Load seed data for evaluation workspace (Tenant 1, Ranks, Users, Departments, Tasks)
                $pdo->exec("SET FOREIGN_KEY_CHECKS = 0;");
                $pdo->exec("SET @@session.sql_mode = CONCAT(@@session.sql_mode, ',NO_AUTO_VALUE_ON_ZERO');");

                // Seed Tenant 1
                $pdo->exec("INSERT INTO `tenants` (`id`, `name`, `subscriptionTier`, `status`, `created_at`, `updated_at`) VALUES (1, 'Acme Maldives Corp', 1, 'active', NOW(), NOW())");

                // Seed Ranks for Tenant 1
                $pdo->exec("INSERT INTO `ranks` (`id`, `tenant_id`, `title`, `level`, `created_at`, `updated_at`) VALUES
                    (1, 1, 'Administrator', 0, NOW(), NOW()),
                    (2, 1, 'Chief Executive', 1, NOW(), NOW()),
                    (3, 1, 'Deputy Chief Executive', 2, NOW(), NOW()),
                    (4, 1, 'Executive / Director', 3, NOW(), NOW()),
                    (5, 1, 'Department Head', 4, NOW(), NOW()),
                    (6, 1, 'Manager', 5, NOW(), NOW()),
                    (7, 1, 'Employee', 6, NOW(), NOW())");

                // Seed Users
                $hash = password_hash('CompanyAdmin123!', PASSWORD_BCRYPT, ['cost' => 12]);
                $pdo->exec("INSERT INTO `users` (`id`, `tenant_id`, `email`, `password_hash`, `first_name`, `last_name`, `rank_id`, `status`, `created_at`, `updated_at`) VALUES
                    (2, 1, 'admin@company.com', '$hash', 'Company', 'Admin', 1, 'active', NOW(), NOW()),
                    (3, 1, 'head@company.com', '$hash', 'Ahmed', 'Shareef', 5, 'active', NOW(), NOW()),
                    (4, 1, 'employee@company.com', '$hash', 'Sara', 'Zahir', 7, 'active', NOW(), NOW())");

                // Seed Department
                $pdo->exec("INSERT INTO `departments` (`id`, `tenant_id`, `name`, `head_user_id`, `created_at`, `updated_at`) VALUES (1, 1, 'Finance & Accounting', 3, NOW(), NOW())");
                $pdo->exec("UPDATE `users` SET `department_id` = 1 WHERE `id` = 3");
                $pdo->exec("UPDATE `users` SET `department_id` = 1, `manager_id` = 3 WHERE `id` = 4");

                // Seed Tasks
                $pdo->exec("INSERT INTO `tasks` (`id`, `tenant_id`, `title`, `description`, `status`, `priority`, `due_date`, `created_by_id`, `department_id`, `created_at`, `updated_at`, `is_recurring`, `recurrence_interval`) VALUES
                    (1, 1, 'Approve Annual Budget Proposals', 'Review and consolidate target department budgets submitted for next financial year. Ensure calculations are double-checked for margin errors.', 'Under Review', 'Critical', DATE_ADD(NOW(), INTERVAL 10 DAY), 2, 1, NOW(), NOW(), 0, NULL),
                    (2, 1, 'Vendor Contract Setup', 'Set up legal compliance parameters and draft formal software service SLA contract.', 'Blocked', 'High', DATE_SUB(NOW(), INTERVAL 2 DAY), 3, 1, NOW(), NOW(), 0, NULL)");

                // Seed Assignments
                $pdo->exec("INSERT INTO `task_assignments` (`tenant_id`, `task_id`, `user_id`, `assigned_at`, `is_active`) VALUES
                    (1, 1, 4, NOW(), 1),
                    (1, 2, 4, NOW(), 1)");

                // Seed Subtasks
                $pdo->exec("INSERT INTO `subtasks` (`tenant_id`, `task_id`, `title`, `status`, `created_at`, `updated_at`) VALUES
                    (1, 1, 'Gather financial data spreadsheets', 'Completed', NOW(), NOW()),
                    (1, 1, 'Execute compliance audit review', 'Completed', NOW(), NOW()),
                    (1, 1, 'Draft Executive summary notes', 'Pending', NOW(), NOW())");

                // Seed Blocker
                $pdo->exec("INSERT INTO `blockers` (`tenant_id`, `task_id`, `reporter_id`, `description`, `created_at`) VALUES
                    (1, 2, 4, 'Awaiting signed compliance check from legal team.', NOW())");

                $pdo->exec("SET FOREIGN_KEY_CHECKS = 1;");

                echo json_encode(['success' => true, 'message' => 'Evaluation seed data loaded successfully.']);
                exit;

            case 'finalize':
                $data = json_decode(file_get_contents('php://input'), true);
                $saEmail = $data['sa_email'] ?? '';
                
                // Write credentials to credentials text file one directory above webroot if possible
                // Otherwise write locally as fallback
                $targetPath = dirname(__DIR__) . '/tascorr-install-credentials.txt';
                $details = "=== TASCORR INSTALLATION DETAILS ===\n";
                $details .= "Installation Date: " . date('Y-m-d H:i:s') . "\n";
                $details .= "Domain: tascorr.thinksafe.mv\n";
                $details .= "Global Superadmin Email: $saEmail\n";
                $details .= "Database Name: " . ($data['dbname'] ?? '') . "\n";
                $details .= "====================================\n";

                @file_put_contents($targetPath, $details);

                // Self delete install.php
                @unlink(__FILE__);

                echo json_encode(['success' => true, 'message' => 'Wizard finalized and deleted. Redirecting...']);
                exit;
        }
    } catch (Exception $e) {
        http_response_code(500);
        echo json_encode(['success' => false, 'message' => $e->getMessage()]);
        exit;
    }
}

