<script>
    // State Store
    const dbConfig = {
        host: 'localhost',
        port: '3306',
        dbname: '',
        username: '',
        password: ''
    };

    let currentStep = 1;
    const totalSteps = 6;
    let saEmailValue = '';

    function showSpinner(button, text) {
        button.disabled = true;
        button.dataset.originalHtml = button.innerHTML;
        button.innerHTML = text + ' <div class="loading-dots"><span></span><span></span><span></span></div>';
    }

    function hideSpinner(button) {
        button.disabled = false;
        button.innerHTML = button.dataset.originalHtml;
    }

    function showAlert(id, text, type) {
        const alert = document.getElementById(id);
        alert.innerText = text;
        alert.className = 'alert alert-' + type;
        alert.style.display = 'block';
    }

    function clearAlerts() {
        document.getElementById('error-alert').style.display = 'none';
        document.getElementById('success-alert').style.display = 'none';
    }

    function goToStep(step) {
        clearAlerts();
        document.getElementById('panel-' + currentStep).classList.remove('active');
        document.querySelector('.progress-step[data-step="' + currentStep + '"]').classList.remove('active');
        if (currentStep < step) {
            document.querySelector('.progress-step[data-step="' + currentStep + '"]').classList.add('completed');
        }

        currentStep = step;
        document.getElementById('panel-' + currentStep).classList.add('active');
        document.querySelector('.progress-step[data-step="' + currentStep + '"]').classList.add('active');
        
        // Progress active line width calculation
        const percent = ((currentStep - 1) / (totalSteps - 1)) * 90;
        document.getElementById('progress-line-active').style.width = percent + '%';
    }

    // Step 1 Click
    document.getElementById('btn-to-step2').addEventListener('click', () => {
        goToStep(2);
    });

    // Step 2 Click (Test DB Connection)
    document.getElementById('btn-test-db').addEventListener('click', async (e) => {
        clearAlerts();
        
        dbConfig.host = document.getElementById('db-host').value;
        dbConfig.port = document.getElementById('db-port').value;
        dbConfig.dbname = document.getElementById('db-name').value;
        dbConfig.username = document.getElementById('db-username').value;
        dbConfig.password = document.getElementById('db-password').value;

        showSpinner(e.target, 'Connecting to server');

        try {
            const response = await fetch('install.php?action=test_db', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(dbConfig)
            });
            const res = await response.json();
            if (res.success) {
                showAlert('success-alert', 'Connection success! Proceeding...', 'success');
                setTimeout(() => goToStep(3), 1000);
            } else {
                showAlert('error-alert', res.message || 'Connection failed.', 'error');
            }
        } catch (err) {
            showAlert('error-alert', 'Network error or connection timeout.', 'error');
        } finally {
            hideSpinner(e.target);
        }
    });

    // Step 3 Click (Run Schema SQL)
    document.getElementById('btn-run-schema').addEventListener('click', async (e) => {
        clearAlerts();
        showSpinner(e.target, 'Installing schema tables');

        try {
            const response = await fetch('install.php?action=install_schema', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(dbConfig)
            });
            const res = await response.json();
            if (res.success) {
                // Show imported tables
                const container = document.getElementById('tables-list-container');
                container.innerHTML = '<strong>Tables Configured:</strong><br>';
                res.tables.forEach(table => {
                    const item = document.createElement('div');
                    item.className = 'table-list-item';
                    item.innerText = table;
                    container.appendChild(item);
                });
                container.style.display = 'block';

                showAlert('success-alert', 'All tables populated successfully.', 'success');
                setTimeout(() => goToStep(4), 2000);
            } else {
                showAlert('error-alert', res.message || 'Execution error.', 'error');
            }
        } catch (err) {
            showAlert('error-alert', 'Execution error or request failure.', 'error');
        } finally {
            hideSpinner(e.target);
        }
    });

    // Step 4 Click (Generate Env Config)
    document.getElementById('btn-gen-env').addEventListener('click', async (e) => {
        clearAlerts();
        showSpinner(e.target, 'Writing configuration');

        try {
            const response = await fetch('install.php?action=save_env', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(dbConfig)
            });
            const res = await response.json();
            if (res.success) {
                showAlert('success-alert', 'Configuration written to .env.', 'success');
                setTimeout(() => goToStep(5), 1500);
            } else {
                showAlert('error-alert', res.message || 'Writing failed.', 'error');
            }
        } catch (err) {
            showAlert('error-alert', 'Network request failed.', 'error');
        } finally {
            hideSpinner(e.target);
        }
    });

    // Step 5 Click (Register Superadmin)
    document.getElementById('btn-create-sa').addEventListener('click', async (e) => {
        clearAlerts();
        saEmailValue = document.getElementById('sa-email').value;
        const saPassword = document.getElementById('sa-password').value;

        if (!saEmailValue || !saPassword) {
            showAlert('error-alert', 'Please enter both email and password.', 'error');
            return;
        }

        showSpinner(e.target, 'Creating administrator account');

        try {
            const response = await fetch('install.php?action=create_superadmin', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({
                    ...dbConfig,
                    sa_email: saEmailValue,
                    sa_password: saPassword
                })
            });
            const res = await response.json();
            if (res.success) {
                showAlert('success-alert', 'Superadmin registered successfully.', 'success');
                setTimeout(() => goToStep(6), 1500);
            } else {
                showAlert('error-alert', res.message || 'Creation failed.', 'error');
            }
        } catch (err) {
            showAlert('error-alert', 'Network request failed.', 'error');
        } finally {
            hideSpinner(e.target);
        }
    });

    // Step 6 Click (Finalize)
    document.getElementById('btn-finalize').addEventListener('click', async (e) => {
        clearAlerts();
        const loadSeed = document.getElementById('seed-checkbox').checked;
        
        showSpinner(e.target, 'Finishing installation');

        try {
            // Optional Seeding
            if (loadSeed) {
                const seedResponse = await fetch('install.php?action=seed_data', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify(dbConfig)
                });
                const seedRes = await seedResponse.json();
                if (!seedRes.success) {
                    showAlert('error-alert', seedRes.message || 'Seeding failed. Proceeding to finalize anyway.', 'error');
                    await new Promise(resolve => setTimeout(resolve, 2000));
                }
            }

            // Finalize & Self Delete
            const finalizeResponse = await fetch('install.php?action=finalize', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({
                    ...dbConfig,
                    sa_email: saEmailValue
                })
            });
            const finRes = await finalizeResponse.json();
            if (finRes.success) {
                showAlert('success-alert', 'Installation Complete! Self-deleting installer... Redirecting to login shortly.', 'success');
                setTimeout(() => {
                    window.location.href = 'https://tascorr.thinksafe.mv';
                }, 3000);
            } else {
                showAlert('error-alert', finRes.message || 'Finalization failed.', 'error');
                hideSpinner(e.target);
            }
        } catch (err) {
            showAlert('error-alert', 'Error finalizing installation.', 'error');
            hideSpinner(e.target);
        }
    });
</script>
